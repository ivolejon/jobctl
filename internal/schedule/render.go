package schedule

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"strconv"
	"strings"
	"time"
	"unicode/utf8"
)

const SystemdMarker = "# Generated by jobctl. Do not edit.\n"

// A plist starts with the XML declaration so that strict XML plist parsers
// accept it. The marker follows the declaration and is still the first thing
// the file says about itself.
const LaunchdMarker = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by jobctl. Do not edit. -->\n"
const LegacyLaunchdMarker = "<!-- Generated by jobctl. Do not edit. -->\n"

type Unit struct {
	Name, Cwd, Executable, Config, StateDir string
	Spec                                    Spec
	Nice                                    *int64
	IOIdle                                  bool
}

type File struct{ Name, GeneratedName, Content string }

func (u Unit) args() []string {
	flags := []string{"--config", u.Config, "--state-dir", u.StateDir, "--trigger", "schedule"}
	if strings.HasPrefix(u.Name, "-") {
		return append(append([]string{u.Executable, "run"}, flags...), "--", u.Name)
	}
	return append([]string{u.Executable, "run", u.Name}, flags...)
}

func Systemd(u Unit) ([]File, error) {
	// WorkingDirectory= consumes a literal path, not an ExecStart-style word.
	if strings.ContainsAny(u.Cwd, "\r\n") || strings.TrimSpace(u.Cwd) != u.Cwd || strings.HasSuffix(u.Cwd, `\`) || !utf8.ValidString(u.Cwd) {
		return nil, fmt.Errorf("WorkingDirectory cannot represent this path in a systemd unit")
	}
	args := u.args()
	for i, arg := range args {
		args[i] = systemdWord(arg)
	}
	name := "jobctl-" + u.Name
	var service, timer strings.Builder
	fmt.Fprintf(&service, "%s[Unit]\nDescription=jobctl: %s\n\n[Service]\nType=oneshot\nTimeoutStartSec=infinity\nWorkingDirectory=%s\nExecStart=:%s\n", SystemdMarker, u.Name, strings.ReplaceAll(u.Cwd, "%", "%%"), strings.Join(args, " "))
	if u.Nice != nil {
		fmt.Fprintf(&service, "Nice=%d\n", *u.Nice)
	}
	if u.IOIdle {
		service.WriteString("IOSchedulingClass=idle\n")
	}
	fmt.Fprintf(&timer, "%s[Unit]\nDescription=Run jobctl job %s\n\n[Timer]\nAccuracySec=1us\n", SystemdMarker, u.Name)
	s := u.Spec
	if s.Interval > 0 {
		period := periodString(s.Interval)
		fmt.Fprintf(&timer, "OnActiveSec=%s\nOnUnitActiveSec=%s\n", period, period)
	} else {
		clock := fmt.Sprintf("%02d:%02d:00", s.Hour, s.Minute)
		if len(s.Days) == 0 {
			fmt.Fprintf(&timer, "OnCalendar=*-*-* %s\n", clock)
		} else {
			for _, day := range s.Days {
				fmt.Fprintf(&timer, "OnCalendar=%s *-*-* %s\n", day.String()[:3], clock)
			}
		}
		timer.WriteString("Persistent=true\n")
	}
	fmt.Fprintf(&timer, "Unit=%s.service\n\n[Install]\nWantedBy=timers.target\n", name)
	return []File{{name + ".service", u.Name + ".service", service.String()}, {name + ".timer", u.Name + ".timer", timer.String()}}, nil
}

func systemdWord(s string) string {
	s = strings.ReplaceAll(s, "%", "%%")
	// Go's ASCII control/quote escapes used here are also recognized by systemd.
	if s != "" && !strings.ContainsAny(s, "\"'\\") && !strings.ContainsFunc(s, func(r rune) bool { return r <= 32 || r == 127 || r == utf8.RuneError }) {
		return s
	}
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c < 32 || c == 127 || !utf8.ValidString(s) && c >= 128:
			fmt.Fprintf(&b, `\x%02x`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func periodString(d time.Duration) string {
	for _, p := range []struct {
		unit   time.Duration
		suffix string
	}{{time.Hour, "h"}, {time.Minute, "m"}, {time.Second, "s"}} {
		if d%p.unit == 0 {
			return strconv.FormatInt(int64(d/p.unit), 10) + p.suffix
		}
	}
	return d.String()
}

func Launchd(u Unit) ([]File, error) {
	var b bytes.Buffer
	label := "com.jobctl." + u.Name
	fmt.Fprintf(&b, "%s<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n<plist version=\"1.0\">\n<dict>\n  <key>Label</key><string>%s</string>\n  <key>ProgramArguments</key>\n  <array>\n", LaunchdMarker, label)
	for _, arg := range u.args() {
		if !utf8.ValidString(arg) || strings.ContainsFunc(arg, func(r rune) bool { return r < 32 && r != '\t' && r != '\r' && r != '\n' || r == 0xfffe || r == 0xffff }) {
			return nil, fmt.Errorf("argument cannot be represented in an XML plist")
		}
		b.WriteString("    <string>")
		_ = xml.EscapeText(&b, []byte(arg))
		b.WriteString("</string>\n")
	}
	b.WriteString("  </array>\n")
	if u.Nice != nil {
		fmt.Fprintf(&b, "  <key>Nice</key><integer>%d</integer>\n", *u.Nice)
	}
	s := u.Spec
	if s.Interval > 0 {
		fmt.Fprintf(&b, "  <key>StartInterval</key><integer>%d</integer>\n", s.Interval/time.Second)
	} else {
		b.WriteString("  <key>StartCalendarInterval</key>\n")
		clock := fmt.Sprintf("<key>Hour</key><integer>%d</integer><key>Minute</key><integer>%d</integer>", s.Hour, s.Minute)
		if len(s.Days) == 0 {
			fmt.Fprintf(&b, "  <dict>%s</dict>\n", clock)
		} else {
			b.WriteString("  <array>\n")
			for _, day := range s.Days {
				fmt.Fprintf(&b, "    <dict><key>Weekday</key><integer>%d</integer>%s</dict>\n", day, clock)
			}
			b.WriteString("  </array>\n")
		}
	}
	b.WriteString("  <key>RunAtLoad</key><false/>\n</dict>\n</plist>\n")
	return []File{{label + ".plist", u.Name + ".plist", b.String()}}, nil
}
